// =================== Alerts & Acknowledgment Models ===================
// Alert represents an alert generated by the system.
type Alert struct {
	ID         int        `json:"id"`
	InstanceID int        `json:"instance_id"`
	Type       string     `json:"type"`     // DB_DISCONNECT, API_UNREACHABLE, HIGH_CPU, MEMORY_LEAK.
	Severity   string     `json:"severity"` // INFO, WARNING, CRITICAL
	Message    string     `json:"message"`
	CreatedAt  time.Time  `json:"created_at"`
	ResolvedAt *time.Time `json:"resolved_at,omitempty"` // Nullable if not resolved
}

// Request to create an alert
type CreateAlertRequest struct {
	InstanceID int    `json:"instance_id" binding:"required"`
	Type       string `json:"type" binding:"required"`
	Severity   string `json:"severity" binding:"required"`
	Message    string `json:"message" binding:"required"`
}

// Response for alert creation
type CreateAlertResponse struct {
	Status  string `json:"status"`
	AlertID int    `json:"alert_id"`
}

// Acknowledgment represents an acknowledgment for an alert.
type Acknowledgment struct {
	ID      int       `json:"id"`
	AlertID int       `json:"alert_id"`
	UserID  int       `json:"user_id"`
	AckTime time.Time `json:"ack_time"`
}

// Request to acknowledge an alert
type AcknowledgeRequest struct {
	UserID int `json:"user_id" binding:"required"`
}

// Response after acknowledging an alert
type AcknowledgeResponse struct {
	Status  string    `json:"status"`
	AlertID int       `json:"alert_id"`
	AckTime time.Time `json:"ack_time"`
}

// UpdateFirmwareRequest represents the request body for updating firmware of a LoxiLB instance.
type UpdateFirmwareRequest struct {
	Cimage *string `json:"cimage" binding:"required" example:"ghcr.io/loxilb-io/loxilb"`
	Ctag   *string `json:"ctag" binding:"required" example:"v0.9.8"`

	// Optional fields
	Description *string `json:"description,omitempty" example:"Updated firmware description"`
	Version     *string `json:"version,omitempty" example:"v0.9.8"`
}

// =================== Pagination Models ===================

// PaginationMeta represents pagination metadata
type PaginationMeta struct {
	Page       int  `json:"page"`        // Current page number
	Limit      int  `json:"limit"`       // Number of items per page
	TotalCount int  `json:"total_count"` // Total number of items
	TotalPages int  `json:"total_pages"` // Total number of pages
	HasNext    bool `json:"has_next"`    // Whether there's a next page
	HasPrev    bool `json:"has_prev"`    // Whether there's a previous page
}

// PaginatedAlertsResponse represents a paginated response for alerts
type PaginatedAlertsResponse struct {
	Data       []Alert        `json:"data"`       // The alert data
	Pagination PaginationMeta `json:"pagination"` // Pagination metadata
}

// EnhancedLoginResponse is the successful login response body.
type EnhancedLoginResponse struct {
	ID    int    `json:"id"`
	Token string `json:"token"`
}

// LoginAttempt represents a failed login attempt for tracking and lockout purposes
type LoginAttempt struct {
	ID           int        `json:"id"`
	Username     string     `json:"username"`
	ClientIP     string     `json:"client_ip"`
	FailedCount  int        `json:"failed_count"`
	LastFailedAt time.Time  `json:"last_failed_at"`
	BlockedUntil *time.Time `json:"blocked_until,omitempty"`
	CreatedAt    time.Time  `json:"created_at"`
	UpdatedAt    time.Time  `json:"updated_at"`
}
